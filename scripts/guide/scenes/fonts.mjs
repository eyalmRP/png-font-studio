// Fonts: import an AI glyph sheet into a new font, edit a glyph, guides, auto-place, try it out, colour variants, files.
import path from 'node:path';
import { SEL, intro } from './common.mjs';

const SHEET = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../../../assets/sheets/bubble-1-capitals.png');

export default async function fonts(r, page) {
  await intro(r, 'Make a font', 'From an AI glyph sheet to a finished font', 'In this video, you’ll turn a sheet of letters into a font, then fine-tune it and make a colour version.');

  r.chapter('The Fonts workspace');
  await r.say('Open Fonts. The interface turns violet here, so you always know you’re working on letters.');
  await r.click(SEL.fontsTab, { dur: 0.8, after: 0.3 });
  await r.done();
  await r.say('Your fonts are listed on the left. Bubble Blue, Orange and Pearl come with the app.');
  await r.spot('.font-list');
  await r.move('.font-item >> nth=1', { dur: 0.7 });
  await r.done();
  await r.spot(null);

  r.chapter('Import a glyph sheet');
  await r.say('Start with a sheet of letters in a grid, drawn by an AI image tool. This guide has prompts you can copy.');
  await r.spot('button:has-text("Import sheets")', { pad: 8 });
  await r.click('button:has-text("Import sheets")', { dur: 0.8, after: 0.4 });
  await r.spot(null);
  await r.done();
  await r.say('Choose the sheet, or drop it straight onto this window.');
  await r.ring('.modal button:has-text("Choose files")');
  const chooser = page.waitForEvent('filechooser');
  await r.click('.modal button:has-text("Choose files")', { dur: 0.8, after: 0.1 });
  await (await chooser).setFiles(SHEET);
  await r.spot(null);
  await r.until(() => document.querySelectorAll('.imp-cell').length > 20, null, 30);
  await r.done(0.4);
  await r.say('The app finds the grid, and removes the background around every letter.');
  await r.spot('.imp-stage');
  await r.camera('.imp-stage', { pad: 30, maxZoom: 1.6 });
  await r.done();
  await r.say('It recognises which sheet this is, and names every cell in reading order: A, B, C, and so on.');
  await r.spot('section.sec:has(.sec-title:text-is("Characters"))');
  await r.camera('section.sec:has(.sec-title:text-is("Characters"))', { pad: 30, maxZoom: 1.8 });
  await r.done();
  await r.say('Check the letters under the sheet. If a cell is wrong, type the right character into it.');
  await r.camera(null);
  await r.spot('.imp-cells');
  await r.move('.imp-cell input >> nth=2', { dur: 0.8 });
  await r.done();
  await r.spot(null);
  await r.scrollTo('section.sec:has(.sec-title:text-is("Import into"))', { dur: 0.8 });
  await r.say('Import into a new font, give it a name, and press Import.');
  await r.spot('section.sec:has(.sec-title:text-is("Import into"))');
  await r.click('section.sec:has(.sec-title:text-is("Import into")) input.text-input', { dur: 0.7, after: 0.1 });
  await r.press('Control+a', { after: 0.1 });
  await r.type('My Bubble', { cps: 10 });
  await r.spot('.modal-foot .btn-primary', { pad: 8 });
  await r.click('.modal-foot .btn-primary', { dur: 0.7, after: 0.2 });
  await r.spot(null);
  await r.until(() => !document.querySelector('.modal-back') && [...document.querySelectorAll('.font-item .name')].some((n) => n.textContent.includes('My Bubble')), null, 60);
  await r.done(0.6);

  r.chapter('Edit a glyph');
  await r.say('Here’s your new font. Click any glyph to edit it.');
  await r.ring('.font-item:has-text("My Bubble")');
  await r.hold(0.8);
  await r.spot(null);
  await r.click('.sheet .cell[aria-label^="A "]', { dur: 0.8, after: 0.4 });
  await r.done();
  await r.say('Drag the letter to move it up or down, or drag the dotted line to change its spacing.');
  await r.spot('.glyph-preview');
  await r.camera('.glyph-preview', { pad: 90, maxZoom: 1.7 });
  await r.drag('.glyph-preview', (m) => ({ x: m.x, y: m.y - 26 }), { dur: 1.0 });
  await r.done(0.2);
  await r.say('The exact numbers are right below: baseline, scale, and the space on each side.');
  await r.spot('.panel-right .grid2 >> nth=0');
  await r.done();
  await r.say('Every change can be undone with Control Z.');
  await r.press('Control+z', { show: ['Ctrl', '+', 'Z'], after: 0.6 });
  await r.keys(null);
  await r.spot(null);
  await r.camera(null);
  await r.done();

  r.chapter('Guides');
  await r.say('Guides show the baseline, cap height, x-height, ascender and descender on every glyph. Turn on the ones you need.');
  await r.spot('.sheet-bar button:has-text("Guides")', { pad: 8 });
  await r.click('.sheet-bar button:has-text("Guides")', { dur: 0.8, after: 0.4 });
  await r.spot(null);
  await r.click('.menu-item:has-text("Image bounds")', { dur: 0.6, after: 0.4 });
  await r.camera('.sheet .cell >> nth=0', { pad: 120, maxZoom: 1.8 });
  await r.done(0.6);
  await r.camera(null);
  await r.click('.sheet-bar button:has-text("Guides")', { dur: 0.6, after: 0.3 });
  await r.click('.menu-item:has-text("Image bounds")', { dur: 0.5, after: 0.3 });

  r.chapter('Auto-place and even sizes');
  await r.scrollTo('.tool-group:has(.tool-head:text-is("Placement"))', { dur: 0.8 });
  await r.say('Auto-place all sets every letter on the baseline for you, with the slight overshoot round letters need.');
  await r.spot('.tool-group:has(.tool-head:text-is("Placement"))');
  await r.click('button:has-text("Auto-place all")', { dur: 0.7, after: 0.3 });
  await r.done();
  await r.say('Even out sizes fixes sheets where each letter was stretched to fill its cell.');
  await r.ring('button:has-text("Even out sizes")');
  await r.move('button:has-text("Even out sizes")', { dur: 0.6 });
  await r.done();
  await r.spot(null);

  r.chapter('Try it out');
  await r.say('Type in the sample line to try your font on any words.');
  await r.spot('input[aria-label="Test text"]');
  await r.click('input[aria-label="Test text"]', { dur: 0.7, after: 0.1 });
  await r.press('Control+a', { after: 0.1 });
  await r.type('HELLO FONTS!', { cps: 10 });
  await r.spot(null);
  await r.done(0.6);

  r.chapter('Colour variants');
  await r.say('Colour variants recolour the whole font from its own artwork. No new sheets needed.');
  await r.click('button.sec-head:has-text("Colour variants")', { dur: 0.8, after: 0.4 });
  await r.scrollTo('button.sec-head:has-text("Colour variants")', { dur: 0.6 });
  await r.spot('section.sec:has(.sec-title:text-is("Colour variants"))');
  await r.done();
  await r.say('Pick a preset, or fine-tune the colours, then create the variant.');
  await r.click('.panel-left .preset:has-text("Gold")', { dur: 0.7, after: 0.8 });
  await r.click('.panel-left .preset:has-text("Green")', { dur: 0.6, after: 0.8 });
  await r.scrollTo('button:has-text("Create variant")', { dur: 0.6, offset: 300 });
  await r.click('button:has-text("Create variant")', { dur: 0.7, after: 0.2 });
  await r.spot(null);
  // the variant is named first (the name of its font and colour is filled in)
  await r.until(() => !!document.querySelector('.modal input.text-input'), null, 5);
  await r.done(0.1);
  await r.say('Give it a name, and press OK.');
  await r.spot('.modal', { pad: 6 });
  await r.hold(0.8);
  await r.click('.modal-foot .btn-primary', { dur: 0.8, after: 0.2 });
  await r.spot(null);
  await r.until(() => document.querySelectorAll('.font-item').length >= 5, null, 60);
  await r.done(0.3);
  await r.say('It appears in your list, ready to use in a title.');
  await r.scrollTo('.font-list', { dur: 0.6 });
  await r.ring('.font-item >> nth=-1');
  await r.done(0.6);
  await r.spot(null);

  r.chapter('Save and Photoshop');
  await r.scrollTo('.tool-group:has(.tool-head:text-is("Files"))', { dur: 0.8 });
  await r.say('Save font file keeps a copy you can share, or open on another computer.');
  await r.spot('.tool-group:has(.tool-head:text-is("Files"))');
  await r.move('button:has-text("Save font file")', { dur: 0.6 });
  await r.done();
  await r.say('Export PSD sends every letter to Photoshop as its own layer. Update from PSD brings your edits back.');
  await r.move('button:has-text("Export PSD")', { dur: 0.6 });
  await r.hold(0.8);
  await r.move('button:has-text("Update from PSD")', { dur: 0.6 });
  await r.done();
  await r.spot(null);
  await r.say('Next, let’s design a title with your font.');
  await r.done(1);
}
fonts.title = 'Make a font';
fonts.poster = 30;
